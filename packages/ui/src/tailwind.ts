function resolveContentPaths(content: string[], cwd: string): string[] {
  const out: string[] = [];
  for (const raw of content) {
    const p = isAbsolute(raw) ? raw : resolve(cwd, raw);
    if (existsSync(p)) out.push(p);
  }
  return out;
}

/** Guess scan roots under `cwd` (`pages/`, `src/`, `app/`). */
export function detectClayTailwindContent(cwd = process.cwd()): string[] {
  const candidates = ['pages', 'src', 'app'];
  return candidates.map((d) => join(cwd, d)).filter((p) => existsSync(p));
}

function resolveTailwindcssRoot(): string {
  const require = createRequire(import.meta.url);
  const tryPkg = (req: NodeJS.Require): string | null => {
    try {
      return dirname(req.resolve('tailwindcss/package.json'));
    } catch {
      return null;
    }
  };
  const fromUi = tryPkg(require);
  if (fromUi) return fromUi;
  try {
    const rootReq = createRequire(
      join(fileURLToPath(new URL('.', import.meta.url)), '../../../package.json'),
    );
    const fromRoot = tryPkg(rootReq);
    if (fromRoot) return fromRoot;
  } catch {
    // ignore
  }
  throw new Error(
    'tailwindcss package not found. Install with: bun add tailwindcss @tailwindcss/cli',
  );
}

function writeInputCss(inputFile: string, sources: string[], appendCss?: string): void {
  mkdirSync(dirname(inputFile), { recursive: true });
  const twRoot = resolveTailwindcssRoot();
  // Absolute CSS imports so builds work even when `.clay/` is outside node_modules.
  const themeCss = join(twRoot, 'theme.css');
  const utilitiesCss = join(twRoot, 'utilities.css');
  const sourceLines = sources.map((s) => `@source ${JSON.stringify(s)};`).join('\n');
  const body = [
    '/* Generated by @close-by/clay — do not edit */',
    `@import ${JSON.stringify(themeCss)} layer(theme);`,
    `@import ${JSON.stringify(utilitiesCss)} layer(utilities);`,
    '',
    sourceLines,
    '',
    THEME_SNIPPET,
    appendCss ? `\n${appendCss.trim()}\n` : '',
  ].join('\n');
  writeFileSync(inputFile, body, 'utf8');
}

function resolveTailwindCliEntry(): string {
  const require = createRequire(import.meta.url);
  const tryPkg = (req: NodeJS.Require): string | null => {
    try {
      const pkgJsonPath = req.resolve('@tailwindcss/cli/package.json');
      return join(dirname(pkgJsonPath), 'dist/index.mjs');
    } catch {
      return null;
    }
  };

  const fromUi = tryPkg(require);
  if (fromUi && existsSync(fromUi)) return fromUi;

  try {
    const rootReq = createRequire(
      join(fileURLToPath(new URL('.', import.meta.url)), '../../../package.json'),
    );
    const fromRoot = tryPkg(rootReq);
    if (fromRoot && existsSync(fromRoot)) return fromRoot;
  } catch {
    // ignore
  }

  throw new Error(
    'Tailwind CLI not found. Install with: bun add tailwindcss @tailwindcss/cli\n' +
      '(shipped with @close-by/clay — ensure the package is installed).',
  );
}

/**
 * Build (and optionally watch) Tailwind CSS for Clay page modules.
 * Returns a stylesheet path suitable for `ui.run({ css })`.
 */
export function ensureClayTailwindCss(options: ClayTailwindOptions): ClayTailwindResult {
  const cwd = options.cwd ?? process.cwd();
  const sources = resolveContentPaths(options.content, cwd);
  if (sources.length === 0) {
    throw new Error(
      'Clay Tailwind: no content paths found. Pass content: ["./pages"] or create a pages/ directory.',
    );
  }

  const outFile = options.outFile
    ? isAbsolute(options.outFile)
      ? options.outFile
      : resolve(cwd, options.outFile)
    : join(cwd, '.clay', 'tailwind.css');
  const inputFile = join(dirname(outFile), 'tailwind.input.css');
  mkdirSync(dirname(outFile), { recursive: true });
  writeInputCss(inputFile, sources, options.appendCss);

  const cliEntry = resolveTailwindCliEntry();
  const buildArgs = [cliEntry, '-i', inputFile, '-o', outFile];

  const built = Bun.spawnSync({
    cmd: [process.execPath, ...buildArgs],
    cwd,
    stdout: 'pipe',
    stderr: 'pipe',
  });
  if (built.exitCode !== 0) {
    const err = built.stderr.toString() || built.stdout.toString() || `exit ${built.exitCode}`;
    throw new Error(`Clay Tailwind build failed:\n${err}`);
  }
  if (!existsSync(outFile)) {
    throw new Error(`Clay Tailwind build produced no file at ${outFile}`);
  }

  let child: ReturnType<typeof Bun.spawn> | null = null;
  if (options.watch) {
    child = Bun.spawn({
      cmd: [process.execPath, ...buildArgs, '--watch'],
      cwd,
      stdout: 'ignore',
      stderr: 'inherit',
      stdin: 'ignore',
    });
  }

  return {
    cssPath: outFile,
    stop: () => {
      if (!child) return;
      try {
        child.kill();
      } catch {
        // already exited
      }
      child = null;
    },
  };
}

/** Merge a Tailwind stylesheet into existing `css` config (append). */
export function mergeClayCss(
  existing: string | string[] | undefined,
  extra: string | string[],
): string[] {
  const a = existing == null ? [] : Array.isArray(existing) ? existing : [existing];
  const b = Array.isArray(extra) ? extra : [extra];
  return [...a, ...b].map((p) => p.trim()).filter(Boolean);
}
