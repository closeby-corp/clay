/**
 * Zero-config Tailwind for Clay apps: scan page modules, emit utilities CSS,
 * inject via `ui.run({ css })` / CLI.
 *
 * Uses `@tailwindcss/cli` (utilities + theme only — client already ships base/preflight).
 */
import { existsSync, mkdirSync, writeFileSync } from 'fs';
import { createRequire } from 'module';
import { dirname, isAbsolute, join, resolve } from 'path';
import { fileURLToPath } from 'url';

export type ClayTailwindOptions = {
  /**
   * Directories/files to scan for `className` / `.classes(...)` strings.
   * Absolute or cwd-relative. Prefer app dirs — never the repo root with `node_modules`.
   */
  content: string[];
  /** Working directory for relative paths. Default `process.cwd()`. */
  cwd?: string;
  /** Output CSS path. Default `<cwd>/.clay/tailwind.css`. */
  outFile?: string;
  /** Keep `@tailwindcss/cli --watch` running after the first build. */
  watch?: boolean;
  /** Extra CSS appended after the generated input (token overrides, keyframes). */
  appendCss?: string;
};

export type ClayTailwindResult = {
  cssPath: string;
  /** Stop the background watch process (if any). */
  stop: () => void;
};

